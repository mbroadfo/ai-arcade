"""Which arcade games on the cabinet are played with a trackball, a spinner or another pointing control, and which
emulator runs each. Offline: reads docs/data/cabinet-controls-catalog.json (MAME 0.251's own input descriptions,
tools/catalog_controls.py) and writes docs/data/pointer-games.json and docs/POINTER_GAMES.md.

    python tools/inventory_pointers.py [--write-games]

--write-games also records each game's device in its own folder, games/arcade/<rom>/controls.json ("pointer").

MAME calls both a spinner and a steering wheel "dial", and a spinner used for Breakout-style games "paddle"; the cabinet's
spinner serves all three. Pedals, light guns and "positional" (Sea Wolf's periscope) are listed because they are not the
panel's buttons or stick, but the trackball and the spinner do not drive them.
"""
import collections
import json

from gamelib import ROOT

CATALOG = ROOT / "docs" / "data" / "cabinet-controls-catalog.json"
OUT_JSON = ROOT / "docs" / "data" / "pointer-games.json"
OUT_MD = ROOT / "docs" / "POINTER_GAMES.md"
# the cabinet device that plays each MAME control type
DEVICE = {"trackball": "trackball", "dial": "spinner", "paddle": "spinner"}
OTHER = ("positional", "lightgun", "pedal")


def classify(game):
    kinds = {c["type"] for c in game["controls"]}
    device = ("trackball" if "trackball" in kinds else "spinner" if kinds & {"dial", "paddle"} else None)
    return device, sorted(kinds & (set(DEVICE) | set(OTHER)))


def write_game_files(rows):
    """Put "pointer": "spinner" or "trackball" in games/<system>/<game>/controls.json for every game that plays with one
    (merging into a file that is there). The framework reads the field; it knows no game by name."""
    import os
    for r in rows:
        if r["device"] not in ("spinner", "trackball"):
            continue
        folder = ROOT / "games" / "arcade" / r["zip"]
        path = folder / "controls.json"
        data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {
            "comment": f"{r['title']} ({r['year']}): this game's controls, where they differ from the cabinet's defaults. Read by pi/mame_human/pad_map.py.",
            "roms": [r["zip"]]}
        data["pointer"] = r["device"]
        os.makedirs(folder, exist_ok=True)
        path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def main():
    import sys
    games = json.loads(CATALOG.read_text(encoding="utf-8"))["games"]
    rows = []
    for g in games:
        device, kinds = classify(g)
        if not kinds:
            continue
        rows.append({"zip": g["zip"], "mame_name": g["mame_name"], "title": g["title"], "year": g["year"],
                     "emulator": g["emulator"], "players": g["players"], "device": device, "mame_controls": kinds,
                     "buttons": max((int(c.get("buttons", 0) or 0) for c in g["controls"]), default=0)})
    rows.sort(key=lambda r: (r["device"] or "~", r["emulator"], r["zip"]))
    OUT_JSON.write_text(json.dumps({"source": "cabinet-controls-catalog.json", "games": rows}, indent=1) + "\n", encoding="utf-8")
    by = collections.defaultdict(list)
    for r in rows:
        by[r["device"] or "other"].append(r)
    lines = ["# Games played with a trackball, a spinner or another pointing control", "",
             "Generated by `tools/inventory_pointers.py` from `docs/data/cabinet-controls-catalog.json`. MAME calls a spinner and a "
             "steering wheel \"dial\"; a spinner used Breakout-style is a \"paddle\". The cabinet's spinner plays both.", ""]
    for device, title in (("trackball", "Trackball"), ("spinner", "Spinner (dial and paddle)"), ("other", "Other (pedal, light gun, positional)")):
        group = by.get(device, [])
        lines += [f"## {title}: {len(group)} games", "", "| Game | ROM | Emulator | Players | Buttons | MAME control |", "|---|---|---|---|---|---|"]
        lines += [f"| {r['title']} ({r['year']}) | {r['zip']} | {r['emulator']} | {r['players']} | {r['buttons']} | {', '.join(r['mame_controls'])} |"
                  for r in group]
        lines.append("")
    tally = collections.Counter((r["device"] or "other", r["emulator"]) for r in rows)
    lines += ["## By emulator", "", "| Device | " + " | ".join(sorted({e for _, e in tally})) + " |", "|---|" + "---|" * len({e for _, e in tally})]
    for device in ("trackball", "spinner", "other"):
        lines.append(f"| {device} | " + " | ".join(str(tally.get((device, e), 0)) for e in sorted({e for _, e in tally})) + " |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if "--write-games" in sys.argv:
        write_game_files(rows)
    print(f"{len(rows)} games: " + ", ".join(f"{d} {len(g)}" for d, g in by.items()))


if __name__ == "__main__":
    main()
