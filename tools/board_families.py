"""Which of the cabinet's games share hardware, from MAME's own driver data, and which of those families an AI kit covers.

    python tools/board_families.py            # asks MAME 0.251 on the Pi (-listxml), writes the two files below

Writes docs/data/board-families.json and docs/BOARD_FAMILIES.md. A family is a MAME driver source file (galaxian/galaxian.cpp:
every game MAME implements on that hardware). A kit (arcadekit/kits/<name>/KIT.json) lists the source files it covers; a game
in one of them can be put on the kit with tools/new_game.py. Games with an AI player today come from tools/ai_setup.py.
"""
import collections
import json
import xml.etree.ElementTree as ET

import paramiko

from ai_setup import ai_games
from gamelib import DEFAULT_PI_HOST, ROOT

CATALOG = ROOT / "docs" / "data" / "cabinet-controls-catalog.json"
OUT_JSON = ROOT / "docs" / "data" / "board-families.json"
OUT_MD = ROOT / "docs" / "BOARD_FAMILIES.md"
KITS = ROOT / "arcadekit" / "kits"


def load_kits(kits_dir=KITS):
    """{kit name: KIT.json} for every kit that has one."""
    return {p.parent.name: json.loads(p.read_text(encoding="utf-8")) for p in sorted(kits_dir.glob("*/KIT.json"))}


def parse_machines(xml_text, wanted):
    """MAME's -listxml -> {machine name: {source, cloneof, cpus, year}} for the machines named in `wanted`."""
    root = ET.fromstring(xml_text[xml_text.index("<mame"):])
    out = {}
    for m in root.iter("machine"):
        if m.get("name") in wanted:
            out[m.get("name")] = {"source": m.get("sourcefile"), "cloneof": m.get("cloneof"),
                                  "cpus": [c.get("name") for c in m.findall("chip") if c.get("type") == "cpu"],
                                  "year": m.findtext("year")}
    return out


def build(catalog_games, machines, kits, ai):
    """The family table: [{source, games: [...], kit, ai_games}] biggest first. `ai` is the set of games with an AI player."""
    kit_for = {src: name for name, k in kits.items() for src in k["sources"]}
    families = collections.defaultdict(list)
    for g in catalog_games:
        info = machines.get(g["mame_name"])
        if info:
            families[info["source"]].append({"zip": g["zip"], "set": g["mame_name"], "title": g["title"], "year": g["year"],
                                             "emulator": g["emulator"], "ai": g["zip"] in ai or g["mame_name"] in ai})
    rows = [{"source": s, "kit": kit_for.get(s), "games": sorted(gs, key=lambda x: x["zip"]),
             "ai_games": [x["zip"] for x in gs if x["ai"]]} for s, gs in families.items()]
    return sorted(rows, key=lambda r: (-len(r["games"]), r["source"]))


def markdown(rows):
    total = sum(len(r["games"]) for r in rows)
    single = sum(1 for r in rows if len(r["games"]) == 1)
    lines = ["# Board families", "",
             "Generated by `tools/board_families.py` from MAME 0.251's driver data. A family is a MAME driver source file: every game on "
             "that hardware. A game in a family with a **kit** can be put on the AI with `tools/new_game.py`; the others need the "
             "family's decoder written first (the first game), after which its siblings cost far less.", "",
             f"{total} games in {len(rows)} families; {single} families have a single game here.", "",
             "| Family (MAME source file) | Games | Kit | AI players now |", "|---|---|---|---|"]
    for r in rows:
        if len(r["games"]) < 2 and not r["kit"] and not r["ai_games"]:
            continue
        names = ", ".join(g["zip"] for g in r["games"][:8]) + (" ..." if len(r["games"]) > 8 else "")
        lines.append(f"| {r['source']} | {len(r['games'])}: {names} | {r['kit'] or ''} | {', '.join(r['ai_games'])} |")
    return "\n".join(lines) + "\n"


def main():
    games = json.loads(CATALOG.read_text(encoding="utf-8"))["games"]
    names = sorted({g["mame_name"] for g in games})
    ssh = paramiko.SSHClient()
    ssh.load_system_host_keys()
    ssh.set_missing_host_key_policy(paramiko.RejectPolicy())
    ssh.connect(DEFAULT_PI_HOST, username="pi", timeout=10)
    try:
        _, out, _ = ssh.exec_command("mame -listxml " + " ".join(names), timeout=600)
        xml_text = out.read().decode(errors="replace")
    finally:
        ssh.close()
    ai = {name.split("/", 1)[1] for name in ai_games()} | {info["romset"] for info in ai_games().values()}
    rows = build(games, parse_machines(xml_text, set(names)), load_kits(), ai)
    OUT_JSON.write_text(json.dumps({"families": rows}, indent=1) + "\n", encoding="utf-8")
    OUT_MD.write_text(markdown(rows), encoding="utf-8")
    print(f"{len(rows)} families; wrote {OUT_JSON.name} and {OUT_MD.name}")


if __name__ == "__main__":
    main()
